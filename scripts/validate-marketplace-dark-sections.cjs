'use strict';
const fs=require('fs');
const html=fs.readFileSync('index.html','utf8');
if(!html.includes('id="apropos-marketplace-dark-sections"')) throw new Error('[marketplace-dark-sections] theme style missing');
const heroStart=html.indexOf('<section class="hero"');
const firstDark=html.indexOf('apropos-dark-section');
if(heroStart<0||firstDark<0||firstDark<heroStart) throw new Error('[marketplace-dark-sections] theme scope invalid');
const heroEnd=html.indexOf('</section>',heroStart);
if(firstDark<heroEnd) throw new Error('[marketplace-dark-sections] hero was incorrectly themed');
console.log('[marketplace-dark-sections] validation passed');
